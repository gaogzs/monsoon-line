/** 把挂点类型翻译成人话 */
function _hpKind(k) {
  return ({ tip: '翼尖', light: '通用', heavy: '重挂', belly: '机腹' })[k] || k;
}

/** 能力标签的中文名 */
function _capLabel(c) {
  return ({ strike: '对地火控', intercept: '高空拦截', ew: '电子战' })[c] || c;
}

/** 射程列的文字 */
function _rngTxt(w) {
  // 定向能吊舱不"飞过去"，它有一个拦截半径
  if (w.kind === 'dew' && w.interceptRange) {
    return '拦截 ' + (w.interceptRange / 1000).toFixed(1) + ' km';
  }
  var r = missileRange(w);
  if (r === null || r === undefined || r <= 0) return '—';
  return r.toFixed(1) + ' km';
}

/** 导引方式描述。导引品质（lead）是这版新加的，直接摆出来对比 */
function _seekerLabel(w) {
  if (w.passive) return '被动';
  if (w.seeker === 'none') return '无制导';
  var s = (w.seeker === 'ir') ? '红外' : '雷达';
  if (w.lead !== undefined) s += ' · 预测 ' + Math.round(w.lead * 100) + '%';
  return s;
}

