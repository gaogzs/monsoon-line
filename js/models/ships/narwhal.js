/* ============================================================
   独角鲸级航空巡洋舰 · 上游公约海军

   外形取"前半段是重武装巡洋舰、后半段是斜角飞行甲板"的航空巡洋舰路线：
     前半  抬高的艏楼（舰艏炮、两座旋转舰空弹架、一座近防炮、成排的反舰 / 舰空弹发射箱）
     中部  右舷一座很高的舰岛（舰桥、相控阵板、桅杆、烟囱）
     后半  整块飞行甲板，左舷边沿向舷外斜出去（约 5°）；着舰区的中线 / 边线 / 拦阻索
           沿同一个方向画；没有弹射器，没有机库升降机之外的东西
   坐标：x 右舷、y 向上（水线 0）、z 舰首；飞行甲板上表面 y = 6.5。
   炮塔与发射架是实体炮塔（见 SHIPS[].mounts / launchers），不在这里画；
   runways（js/data/ships/narwhal.js）取斜角甲板的前端，要与这里的着舰轴线对上。
   ============================================================ */
Registry.model({
  id: 'narwhal', order: 285, settle: true,
  build: function (L) {
    var V = L.V, C = L.C, MB = L.MB, mast = L.mast, house = L.house, done = L.done;
    var b = new MB();
    var TOP = 6.5;                                   // 飞行甲板上表面
    var KANG = 0.0909;                               // 着舰轴线与中线夹角的正切（≈5.2°）
    function axisX(z) { return -6 + KANG * (z + 60); }   // 着舰轴线 x(z)，z 越靠前越向右舷

    b.hull([
      { z: 98, w: 0.8, y0: -1.2, y1: 6.8 },
      { z: 84, w: 3.8, y0: -3.0, y1: 6.4 },
      { z: 60, w: 7.4, y0: -3.6, y1: 6.4 },
      { z: 24, w: 9.4, y0: -3.8, y1: 6.4 },
      { z: -12, w: 10.0, y0: -3.8, y1: 6.4 },
      { z: -60, w: 10.4, y0: -3.6, y1: 6.4 },
      { z: -96, w: 9.6, y0: -3.4, y1: 6.4 },
      { z: -98, w: 8.8, y0: -3.2, y1: 6.4 }
    ], C.hull, C.deck, C.boot);

    function stripe(x0, z0, x1, z1, w, col, y) {
      var dx = x1 - x0, dz = z1 - z0, l = Math.sqrt(dx * dx + dz * dz) || 1;
      var nx = dz / l * w / 2, nz = -dx / l * w / 2, yy = y || (TOP + 0.06);
      b.wing(V(x0 + nx, yy, z0 + nz), V(x1 + nx, yy, z1 + nz), V(x1 - nx, yy, z1 - nz), V(x0 - nx, yy, z0 - nz), col);
    }

    /* ---------- 后半：飞行甲板 ---------- */
    // 左舷斜出去的甲板外沿：从 z = -14 的 x = -8.6 斜到舰尾的 x = -17.6
    b.wing(V(10.4, TOP, -98), V(10.4, TOP, -14), V(-8.6, TOP, -14), V(-17.6, TOP, -98), C.deck);
    // 探出舷外那一块的下面托一个舷台，不然甲板悬在半空
    b.box(-8.5, 4.6, -56, 16, 2.4, 84, C.hull2);
    // 着舰区：中线 + 两条边线 + 四道拦阻索
    stripe(axisX(-96), -96, axisX(-20), -20, 0.7, C.white);
    stripe(axisX(-96) - 5, -96, axisX(-20) - 5, -20, 0.5, C.yellow);
    stripe(axisX(-96) + 5, -96, axisX(-20) + 5, -20, 0.5, C.yellow);
    var wires = [-88, -78, -68, -58];
    for (var wi = 0; wi < wires.length; wi++) {
      var cx = axisX(wires[wi]);
      stripe(cx - 4.4, wires[wi], cx + 4.4, wires[wi], 0.35, C.metal, TOP + 0.1);
    }
    // 甲板边缘警示带：右舷整段、左舷斜边外沿
    stripe(10.2, -96, 10.2, -16, 0.7, C.yellow);
    stripe(-17.2, -96, -8.4, -16, 0.7, C.yellow);
    // 右舷停机位的升降机（甲板上颜色不同的一块方板）
    b.box(4.5, TOP + 0.1, -40, 8, 0.25, 13, C.metal);

    /* ---------- 前半：抬高的艏楼与武器 ---------- */
    b.box(0, 8.4, 54, 11, 4.0, 48, C.hull2);                // 艏楼：y 6.4 … 10.4，z 30 … 78
    b.box(-2.8, 11.2, 58, 2.4, 1.6, 12, C.hull);            // 成排的发射箱（装饰，实体发射架见 launchers）
    b.box(2.8, 11.2, 58, 2.4, 1.6, 12, C.hull);
    b.box(0, 11.2, 50, 2.4, 1.6, 8, C.hull);
    // 舰艏炮、旋转舰空弹架、近防炮：实体炮塔

    /* ---------- 中部：右舷高舰岛 ---------- */
    house(b, 7.4, 8, 7.0, 14.0, 34.0, 6.4, C.hull2, C.hull);
    house(b, 7.2, 10, 5.8, 6.0, 20.0, 20.5, C.hull, C.hull2);
    b.box(7.2, 24.0, 10, 6.0, 1.4, 20.4, C.canopy);          // 舰桥一圈玻璃
    b.box(7.4, 14.0, 25.3, 5.4, 6.0, 0.5, C.dark);           // 前面的相控阵板
    b.box(3.7, 14.0, 8, 0.5, 6.0, 6.0, C.dark);              // 左面的相控阵板
    mast(b, 7.4, 2, 26.5, 24, 1.4, 0.4, C.hull2);            // 主桅
    mast(b, 7.0, 18, 26.5, 16, 0.9, 0.3, C.hull2);           // 前桅
    b.tube(V(8, 19, -16), V(8, 26, -16), 2.2, 1.8, 6, C.hull2, C.boot);   // 烟囱

    return done(b, { span: 28, len: 196, ground: true, sea: true, radius: 62 });
  }
});
