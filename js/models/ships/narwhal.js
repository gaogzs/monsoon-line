/* ============================================================
   独角鲸级航空巡洋舰 · 上游公约海军

   布局参照基辅级（明斯克号）航空巡洋舰：
     后 2/3  飞行甲板：从舰尾一直铺到舰体中部偏前；左舷整块向舷外探出（舷台），
             着舰轴线与中线夹约 4.5°，越往前越偏向左舷 —— 飞机顺着轴线往前滑，
             复飞时从左舷飞出去，不会撞上右舷的舰岛
     中部    右舷一座很高的舰岛（舰桥、相控阵板、桅杆）和烟囱，压在甲板前端的右侧
     前 1/3  抬高的艏楼：舰艏炮、两座旋转舰空弹架、一座近防炮、成排的反舰 / 舰空弹发射箱
   没有弹射器、没有机库升降机之外的东西 —— 是巡洋舰多出一块能给飞机补给的后甲板。

   坐标：x 右舷、y 向上（水线 0）、z 舰首；飞行甲板上表面 y = 6.5。
   着舰轴线：x(z) = 0.5 − KANG·(z + 96)，z 越大 x 越小（向左舷）。
   炮塔与发射架是实体炮塔（见 SHIPS[].mounts / launchers），不在这里画；
   runways（js/data/ships/narwhal.js）取着舰轴线的前端，要与这里对上。
   ============================================================ */
Registry.model({
  id: 'narwhal', order: 285, settle: true,
  build: function (L) {
    var V = L.V, C = L.C, MB = L.MB, mast = L.mast, house = L.house, done = L.done;
    var b = new MB();
    var TOP = 6.5;                                   // 飞行甲板上表面
    var KANG = 0.0787;                               // 着舰轴线与中线夹角的正切（≈4.5°）
    function axisX(z) { return 0.5 - KANG * (z + 96); }

    b.hull([
      { z: 98, w: 0.8, y0: -1.2, y1: 6.8 },
      { z: 84, w: 3.8, y0: -3.0, y1: 6.4 },
      { z: 60, w: 7.4, y0: -3.6, y1: 6.4 },
      { z: 30, w: 9.6, y0: -3.8, y1: 6.4 },
      { z: -10, w: 10.2, y0: -3.8, y1: 6.4 },
      { z: -60, w: 10.4, y0: -3.6, y1: 6.4 },
      { z: -96, w: 10.2, y0: -3.4, y1: 6.4 },
      { z: -98, w: 9.8, y0: -3.2, y1: 6.4 }
    ], C.hull, C.deck, C.boot);

    function stripe(x0, z0, x1, z1, w, col, y) {
      var dx = x1 - x0, dz = z1 - z0, l = Math.sqrt(dx * dx + dz * dz) || 1;
      var nx = dz / l * w / 2, nz = -dx / l * w / 2, yy = y || (TOP + 0.06);
      b.wing(V(x0 + nx, yy, z0 + nz), V(x1 + nx, yy, z1 + nz), V(x1 - nx, yy, z1 - nz), V(x0 - nx, yy, z0 - nz), col);
    }
    // 双面四边形（舷台的侧裙边，不确定朝哪边可见，两种绕向都画）
    function skirt(a, c, drop, col) {
      b.wing(V(a[0], TOP, a[1]), V(c[0], TOP, c[1]), V(c[0], TOP - drop, c[1]), V(a[0], TOP - drop, a[1]), col);
      b.wing(V(a[0], TOP - drop, a[1]), V(c[0], TOP - drop, c[1]), V(c[0], TOP, c[1]), V(a[0], TOP, a[1]), col);
    }

    /* ---------- 后 2/3：飞行甲板 ---------- */
    // 主甲板：舰尾 z = -98 一直到 z = +36（舰体中部偏前），右舷边沿 x = +10.4
    b.wing(V(10.4, TOP, -98), V(10.4, TOP, 36), V(-9.8, TOP, 36), V(-9.8, TOP, -98), C.deck);
    // 左舷舷台：外沿从舰尾 (-10.4, -98) 沿着舰轴线的角度斜出去，到 z = +14 处最宽 (-19.2)，
    // 再斜着收回舰体 (-9.8, +36)
    b.wing(V(-9.8, TOP, -98), V(-9.8, TOP, 36), V(-19.2, TOP, 14), V(-10.4, TOP, -98), C.deck);
    skirt([-10.4, -98], [-19.2, 14], 2.6, C.hull2);
    skirt([-19.2, 14], [-9.8, 36], 2.6, C.hull2);

    // 着舰区：中线 + 两条边线 + 拦阻索（轴线越往前越偏左舷）
    stripe(axisX(-96), -96, axisX(12), 12, 0.7, C.white);
    stripe(axisX(-96) - 5, -96, axisX(12) - 5, 12, 0.5, C.yellow);
    stripe(axisX(-96) + 5, -96, axisX(12) + 5, 12, 0.5, C.yellow);
    var wires = [-86, -76, -66, -56];
    for (var wi = 0; wi < wires.length; wi++) {
      var cx = axisX(wires[wi]);
      stripe(cx - 4.4, wires[wi], cx + 4.4, wires[wi], 0.35, C.metal, TOP + 0.1);
    }
    // 甲板边缘警示带：右舷整段、左舷舷台外沿
    stripe(10.2, -96, 10.2, 34, 0.7, C.yellow);
    stripe(-10.2, -96, -19.0, 14, 0.7, C.yellow);
    // 升降机（甲板上颜色不同的一块方板）：右舷停机位和舷台上各一块
    b.box(5.2, TOP + 0.1, -40, 8, 0.25, 13, C.metal);
    b.box(-14, TOP + 0.1, -30, 8, 0.25, 13, C.metal);

    /* ---------- 前 1/3：抬高的艏楼与武器 ---------- */
    b.box(0, 8.4, 62, 11, 4.0, 44, C.hull2);                // 艏楼：y 6.4 … 10.4，z 40 … 84
    b.box(-2.8, 11.2, 54, 2.4, 1.6, 10, C.hull);            // 成排的发射箱（装饰，实体发射架见 launchers）
    b.box(2.8, 11.2, 54, 2.4, 1.6, 10, C.hull);
    b.box(-2.8, 11.2, 66, 2.4, 1.6, 6, C.hull);
    b.box(2.8, 11.2, 66, 2.4, 1.6, 6, C.hull);
    // 舰艏炮、旋转舰空弹架、近防炮：实体炮塔

    /* ---------- 中部：右舷高舰岛 ---------- */
    house(b, 7.6, 14, 6.4, 14.0, 30.0, 6.4, C.hull2, C.hull);
    house(b, 7.4, 16, 5.4, 6.0, 18.0, 20.5, C.hull, C.hull2);
    b.box(7.4, 24.0, 16, 5.6, 1.4, 18.4, C.canopy);          // 舰桥一圈玻璃
    b.box(7.6, 14.0, 29.3, 4.8, 6.0, 0.5, C.dark);           // 前面的相控阵板
    b.box(4.5, 14.0, 14, 0.5, 6.0, 6.0, C.dark);             // 左面的相控阵板
    mast(b, 7.6, 8, 26.5, 24, 1.4, 0.4, C.hull2);            // 主桅
    mast(b, 7.2, 22, 26.5, 16, 0.9, 0.3, C.hull2);           // 前桅
    b.tube(V(8, 19, -6), V(8, 26, -6), 2.2, 1.8, 6, C.hull2, C.boot);     // 烟囱

    return done(b, { span: 38.4, len: 196, ground: true, sea: true, radius: 62 });
  }
});
