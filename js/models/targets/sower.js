/* ============================================================
   「灰烬」级播撒机 —— 下游的反凝结核投送平台
   体型大、速度低、自卫火力弱；载荷一旦投下就无法回收
   ============================================================ */
Registry.model({
  id: 'sower', order: 60,
  build: function (L) {
    var V = L.V, C = L.C, MB = L.MB, done = L.done;
    var b = new MB();
    b.fuselage([
      { z: 16.0, w: 0.6, h: 0.6 },
      { z: 12.0, w: 1.6, h: 1.5 },
      { z: 4.0, w: 2.6, h: 2.2 },
      { z: -8.0, w: 2.7, h: 2.3 },
      { z: -18.0, w: 2.0, h: 1.9 },
      { z: -24.0, w: 1.8, h: 1.7 }
    ], C.navy, C.dark);

    b.foil(V(2.2, 0.20, 4.0), V(19.0, 1.20, -6.0), V(19.0, 1.20, -11.0), V(2.2, 0.20, -9.0), C.navy2);
    b.foilM(V(2.2, 0.20, 4.0), V(19.0, 1.20, -6.0), V(19.0, 1.20, -11.0), V(2.2, 0.20, -9.0), C.navy2);

    b.foil(V(1.8, 2.0, -12.0), V(2.1, 7.0, -17.0), V(2.1, 7.0, -21.5), V(1.8, 2.0, -20.0), C.navy2);
    b.foilM(V(1.8, 2.0, -12.0), V(2.1, 7.0, -17.0), V(2.1, 7.0, -21.5), V(1.8, 2.0, -20.0), C.navy2);

    /* 尾部双喷口。以前是四个（±1.6 r1.35 与 ±2.4 r1.05），彼此穿插，还比机尾末端宽一大截，
       像两只大桶焊在尾巴上；机尾放宽一点，两个喷口前端圆环整个落进末端截面里。 */
    b.tube(V(0.9, 0, -23.7), V(0.9, 0, -25.6), 0.58, 0.54, 10, C.nozzle, C.darker);
    b.tube(V(-0.9, 0, -23.7), V(-0.9, 0, -25.6), 0.58, 0.54, 10, C.nozzle, C.darker);

    b.quad(b.pt(0, 2.15, 13.5), b.pt(1.1, 2.30, 10.0), b.pt(0, 3.10, 8.0), b.pt(-1.1, 2.30, 10.0), C.canopy);

    return done(b, { span: 38.0, len: 42.5 });
  }
});
