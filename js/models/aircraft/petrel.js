/* ============================================================
   F-9「海燕」Petrel —— 高空高速截击机
   大三角翼 + 双发 + 外倾双垂尾。为了在两万米以上截击而生的气动：
   翼载高、后掠大、结构简单，低空盘旋一塌糊涂。
   ============================================================ */
Registry.model({
  id: 'petrel', order: 410,
  build: function (L) {
    var V = L.V, C = L.C, MB = L.MB, done = L.done;
    var b = new MB();
    b.fuselage([
      { z: 11.4, w: 0.08, h: 0.08 },
      { z: 9.0, w: 0.44, h: 0.42 },
      { z: 6.0, w: 0.84, h: 0.78 },
      { z: 3.0, w: 1.30, h: 1.14 },
      { z: -1.0, w: 1.56, h: 1.28 },
      { z: -5.5, w: 1.68, h: 1.32 },
      { z: -9.6, w: 1.44, h: 1.14 }
    ], C.body, C.body3);

    // 大三角翼
    b.foil(V(1.42, -0.30, 2.6), V(6.6, -0.62, -6.4),
      V(6.6, -0.62, -7.7), V(1.52, -0.30, -6.1), C.wing);
    b.foilM(V(1.42, -0.30, 2.6), V(6.6, -0.62, -6.4),
      V(6.6, -0.62, -7.7), V(1.52, -0.30, -6.1), C.wing);

    // 外倾双垂尾
    b.foil(V(0.70, 1.00, -6.2), V(2.30, 3.40, -9.4),
      V(2.30, 3.40, -10.3), V(0.70, 1.00, -7.3), C.wing2);
    b.foilM(V(0.70, 1.00, -6.2), V(2.30, 3.40, -9.4),
      V(2.30, 3.40, -10.3), V(0.70, 1.00, -7.3), C.wing2);

    // 平尾（小）
    b.foil(V(1.5, 0.10, -6.6), V(3.4, -0.10, -9.4),
      V(3.4, -0.10, -10.2), V(1.5, 0.10, -8.2), C.wing2);
    b.foilM(V(1.5, 0.10, -6.6), V(3.4, -0.10, -9.4),
      V(3.4, -0.10, -10.2), V(1.5, 0.10, -8.2), C.wing2);

    // 双尾喷口
    b.tube(V(0.76, -0.12, -9.4), V(0.76, -0.12, -10.5), 0.44, 0.42, 8, C.nozzle, C.darker);
    b.tube(V(-0.76, -0.12, -9.4), V(-0.76, -0.12, -10.5), 0.44, 0.42, 8, C.nozzle, C.darker);

    // 进气道
    b.box(0.92, -0.36, 1.4, 0.46, 0.86, 3.6, C.dark);
    b.box(-0.92, -0.36, 1.4, 0.46, 0.86, 3.6, C.dark);

    // 座舱盖
    b.quad(b.vt(V(0, 1.00, 8.6)), b.vt(V(0.44, 0.72, 5.2)),
      b.vt(V(0, 0.58, 3.8)), b.vt(V(-0.44, 0.72, 5.2)), C.canopy);

    return done(b, {
      span: 13.2, len: 22.9,
      sweepAlt: null
    });
  }
});
