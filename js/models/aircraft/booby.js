/* ============================================================
   G-6「鲣鸟」Booby —— 近距空中支援攻击机
   大展弦比平直翼 + 双发翼根布局 + 38 mm 钛合金装甲浴缸
   ============================================================ */
Registry.model({
  id: 'booby', order: 30,
  build: function (L) {
    var V = L.V, C = L.C, MB = L.MB, done = L.done;
    var b = new MB();
    b.fuselage([
      { z: 8.8, w: 0.34, h: 0.50 },
      { z: 6.2, w: 0.98, h: 0.98 },
      { z: 2.2, w: 1.34, h: 1.22 },
      { z: -3.0, w: 1.44, h: 1.28 },
      { z: -7.0, w: 1.22, h: 1.12 },
      { z: -9.2, w: 1.02, h: 0.96 }
    ], C.green, C.green2);

    // 大展弦比平直翼
    b.foil(V(1.30, 0.15, 2.0), V(8.6, 0.55, 0.5), V(8.6, 0.55, -2.6), V(1.30, 0.15, -3.2), C.wing2);
    b.foilM(V(1.30, 0.15, 2.0), V(8.6, 0.55, 0.5), V(8.6, 0.55, -2.6), V(1.30, 0.15, -3.2), C.wing2);

    // 双垂尾 + 平尾
    b.foil(V(1.05, 1.15, -6.1), V(1.38, 3.30, -7.2), V(1.38, 3.30, -9.2), V(1.05, 1.15, -9.0), C.green2);
    b.foilM(V(1.05, 1.15, -6.1), V(1.38, 3.30, -7.2), V(1.38, 3.30, -9.2), V(1.05, 1.15, -9.0), C.green2);
    b.foil(V(1.15, 0.35, -6.2), V(4.1, 0.35, -6.9), V(4.1, 0.35, -8.7), V(1.15, 0.35, -8.3), C.wing2);
    b.foilM(V(1.15, 0.35, -6.2), V(4.1, 0.35, -6.9), V(4.1, 0.35, -8.7), V(1.15, 0.35, -8.3), C.wing2);

    // 翼下发动机吊舱
    b.fuselage([{ z: 1.0, w: 0.52, h: 0.52, y: -0.2 }, { z: -2.0, w: 0.66, h: 0.66, y: -0.2 }, { z: -5.0, w: 0.60, h: 0.60, y: -0.2 }], C.body3);
    // 上面那段的 x 需要偏移：这里用 tube 更直接
    b.tube(V(2.35, -0.30, 1.2), V(2.35, -0.30, -5.2), 0.62, 0.58, 8, C.body3, C.darker);
    b.tube(V(-2.35, -0.30, 1.2), V(-2.35, -0.30, -5.2), 0.62, 0.58, 8, C.body3, C.darker);
    b.tube(V(2.35, -0.30, -5.2), V(2.35, -0.30, -5.9), 0.42, 0.40, 8, C.nozzle, C.darker);
    b.tube(V(-2.35, -0.30, -5.2), V(-2.35, -0.30, -5.9), 0.42, 0.40, 8, C.nozzle, C.darker);

    // 机头 CEL-7 4 管 30mm 转膛炮
    b.tube(V(0.28, -0.78, 7.0), V(0.28, -0.78, 10.2), 0.17, 0.17, 6, C.rod);
    b.tube(V(-0.28, -0.78, 7.0), V(-0.28, -0.78, 10.2), 0.17, 0.17, 6, C.rod);

    b.quad(b.pt(0, 0.90, 5.2), b.pt(0.62, 1.00, 3.9), b.pt(0, 1.55, 3.0), b.pt(-0.62, 1.00, 3.9), C.canopy);

    return done(b, { span: 17.2, len: 19.4 });
  }
});
