/* ============================================================
   J-6「蝠鲼」Manta —— 重型运输机
   名字是蝠鲼，外形也是：宽扁的飞翼式机体、圆润的翼尖、机头两侧向前探出的"头鳍"、
   一根细长的尾刺，翼上方四台发动机，背部一道货舱隆起。
   长 40 × 展 47 m；慢、大、不武装。
   ============================================================ */
Registry.model({
  id: 'manta', order: 443,
  build: function (L) {
    var V = L.V, C = L.C, MB = L.MB, done = L.done;
    var b = new MB();

    // 机身：又宽又扁的中央体
    b.fuselage([
      { z: 14.0, w: 0.80, h: 0.50 },
      { z: 9.0, w: 2.60, h: 1.20 },
      { z: 3.0, w: 4.40, h: 1.80 },
      { z: -4.0, w: 4.60, h: 1.90 },
      { z: -10.0, w: 3.20, h: 1.40 },
      { z: -14.0, w: 1.00, h: 0.70 }
    ], C.body, C.body3);

    function wing(p1, p2, p3, p4, col) { b.foil(p1, p2, p3, p4, col); b.foilM(p1, p2, p3, p4, col); }

    // 宽大的飞翼：翼根前缘在机身中部，后掠，后缘微微后凸；最外侧一小块圆润的翼尖
    wing(V(4.0, 0.2, 8.0), V(20.0, 0.0, -2.6), V(20.0, 0.0, -8.0), V(4.2, 0.2, -12.0), C.wing);
    wing(V(20.0, 0.0, -2.6), V(23.4, -0.4, -6.2), V(23.4, -0.4, -8.6), V(20.0, 0.0, -8.0), C.wing2);

    // 头鳍：机头两侧向前探出的一对小翼（蝠鲼的"角"）
    wing(V(1.4, 0.0, 11.5), V(3.4, 0.0, 15.2), V(3.4, 0.0, 13.6), V(2.0, 0.0, 9.2), C.wing2);

    // 尾刺：细长的一根，根部两片小垂尾
    b.tube(V(0, 0.2, -14), V(0, 0.2, -26), 0.42, 0.12, 6, C.wing2, C.dark);
    wing(V(1.2, 0.9, -12), V(1.9, 4.8, -16), V(1.9, 4.8, -18.2), V(1.2, 0.9, -16.5), C.wing2);

    // 翼上方四台发动机（短舱 + 前进气口 + 后喷口）
    var ex = [5.6, 10.6];
    for (var side = -1; side <= 1; side += 2) {
      for (var i = 0; i < ex.length; i++) {
        var x = side * ex[i];
        b.tube(V(x, 1.5, -0.5), V(x, 1.5, -9.0), 1.0, 0.95, 8, C.body3, C.dark);
        b.box(x, 1.5, -0.4, 1.4, 1.4, 0.4, C.dark);
        b.tube(V(x, 1.5, -9.0), V(x, 1.5, -10.6), 0.8, 0.7, 8, C.nozzle, C.darker);
      }
    }

    // 背部货舱隆起
    b.box(0, 2.1, -3, 2.2, 1.0, 12, C.body3);

    // 驾驶舱玻璃
    b.quad(b.vt(V(0, 1.45, 8.6)), b.vt(V(1.1, 1.35, 6.2)),
      b.vt(V(0, 1.55, 4.6)), b.vt(V(-1.1, 1.35, 6.2)), C.canopy);

    return done(b, { span: 47, len: 41, sweepAlt: null });
  }
});
