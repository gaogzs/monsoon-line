/* ============================================================
   D-27「海马」Seahorse —— 轻型舰载垂直起降战斗机
   短小的单发机，没有跑道也能起降，所以和普通战斗机差得最多的是"喷口"：
     四个可偏转的喷口   机身中段两侧一对（朝下托举时就在重心附近）、机尾一对；画成短粗的黑喷管
     座舱后的升力风扇舱盖  机背上一块平的深色矩形（风扇向下吹，舱盖盖着）
     高位的梯形翼       翼面平直短粗，翼尖有一个悬挂点
     侧进气             机身两侧嵌进去的矩形进气口，在机翼前
     单垂尾 + 小平尾    尾部收得很短，给喷口让位
   坐标 x 右、y 上、z 机头；长 16.0 × 展 8.6 m。
   ============================================================ */
Registry.model({
  id: 'seahorse', order: 430,
  build: function (L) {
    var V = L.V, C = L.C, MB = L.MB, done = L.done;
    var b = new MB();
    // 机身：短而粗，机头收得快
    b.fuselage([
      { z: 7.4, w: 0.08, h: 0.08 },
      { z: 6.0, w: 0.45, h: 0.40 },
      { z: 3.5, w: 0.85, h: 0.70 },
      { z: 0.5, w: 1.05, h: 0.80 },
      { z: -3.0, w: 1.00, h: 0.80 },
      { z: -6.0, w: 0.85, h: 0.70 },
      { z: -7.6, w: 0.60, h: 0.50 }
    ], C.body, C.body3);

    function wing(p1, p2, p3, p4, col) { b.foil(p1, p2, p3, p4, col); b.foilM(p1, p2, p3, p4, col); }

    // 高位梯形翼：前缘后掠约 35°，后缘几乎垂直机身，翼尖短而厚
    wing(V(1.0, 0.35, 2.0), V(4.3, 0.25, -2.4), V(4.3, 0.25, -4.2), V(1.0, 0.35, -5.0), C.wing);
    // 小平尾（低位）
    wing(V(0.9, 0.10, -6.0), V(3.3, 0.05, -7.2), V(3.3, 0.05, -7.9), V(0.9, 0.10, -7.6), C.wing2);
    // 单垂尾
    b.foil(V(0, 0.8, -4.5), V(0, 3.3, -6.5), V(0, 3.3, -7.4), V(0, 0.8, -7.3), C.wing2);

    // 机身两侧的矩形进气口：嵌进机身（内移，和机身截面相交），在机翼前
    b.box(1.10, 0.05, 1.6, 0.8, 0.9, 2.2, C.dark);
    b.box(-1.10, 0.05, 1.6, 0.8, 0.9, 2.2, C.dark);

    // 升力风扇舱盖：座舱后机背上一块平的深色矩形
    b.quad(b.vt(V(0.6, 0.83, 0.6)), b.vt(V(0.6, 0.83, -1.0)),
      b.vt(V(-0.6, 0.83, -1.0)), b.vt(V(-0.6, 0.83, 0.6)), C.dark);

    // 四个可偏转喷口：机身中段两侧一对（朝下时在重心附近）+ 机尾一对
    b.tube(V(1.20, -0.40, -1.4), V(1.20, -0.40, -3.2), 0.46, 0.38, 10, C.nozzle, C.darker);
    b.tube(V(-1.20, -0.40, -1.4), V(-1.20, -0.40, -3.2), 0.46, 0.38, 10, C.nozzle, C.darker);
    b.tube(V(0.45, 0.00, -7.3), V(0.45, 0.00, -8.6), 0.42, 0.36, 8, C.nozzle, C.darker);
    b.tube(V(-0.45, 0.00, -7.3), V(-0.45, 0.00, -8.6), 0.42, 0.36, 8, C.nozzle, C.darker);

    // 座舱盖
    b.quad(b.vt(V(0, 0.98, 3.6)), b.vt(V(0.55, 0.82, 1.8)),
      b.vt(V(0, 0.76, 0.2)), b.vt(V(-0.55, 0.82, 1.8)), C.canopy);

    return done(b, { span: 8.6, len: 16.0, sweepAlt: null });
  }
});
