/* ============================================================
   F-12「塘鹅」Gannet —— 国土防卫重型战斗机
   鸭翼布局：机头后方一对大鸭翼 + 切角大三角翼（后缘平直）+ 垂直双垂尾分得很开、没有平尾，
   机腹两侧是方形大进气口，双发并排。体型比海燕厚一圈，靠结构吃伤害，不靠机动。
   ============================================================ */
Registry.model({
  id: 'gannet', order: 411,
  build: function (L) {
    var V = L.V, C = L.C, MB = L.MB, done = L.done;
    var b = new MB();
    b.fuselage([
      { z: 12.4, w: 0.08, h: 0.08 },
      { z: 10.0, w: 0.50, h: 0.45 },
      { z: 6.5, w: 1.00, h: 0.90 },
      { z: 2.5, w: 1.60, h: 1.35 },
      { z: -2.0, w: 1.90, h: 1.50 },
      { z: -7.0, w: 1.95, h: 1.50 },
      { z: -10.4, w: 1.60, h: 1.25 }
    ], C.body, C.body3);

    function wing(p1, p2, p3, p4, col) { b.foil(p1, p2, p3, p4, col); b.foilM(p1, p2, p3, p4, col); }

    // 大鸭翼：机头后方、座舱两侧，翼展 11 m，比一般战斗机的鸭翼大得多
    wing(V(1.1, 0.35, 7.0), V(5.4, 0.25, 3.6), V(5.4, 0.25, 2.2), V(1.5, 0.35, 3.8), C.wing2);

    // 切角大三角翼：前缘后掠，翼尖被"切"掉，后缘是直的
    wing(V(1.8, -0.3, 2.5), V(7.8, -0.5, -5.0), V(7.8, -0.5, -8.4), V(1.9, -0.3, -8.6), C.wing);

    // 双垂尾：垂直，分得很开（x = ±1.5），没有平尾（以前外倾约 30°，注释却写 15°）
    wing(V(1.5, 0.95, -6.4), V(1.5, 4.1, -9.0), V(1.5, 4.1, -10.4), V(1.5, 0.95, -9.8), C.wing2);

    // 双发并排的尾喷口
    b.tube(V(1.0, -0.10, -10.2), V(1.0, -0.10, -11.6), 0.55, 0.50, 8, C.nozzle, C.darker);
    b.tube(V(-1.0, -0.10, -10.2), V(-1.0, -0.10, -11.6), 0.55, 0.50, 8, C.nozzle, C.darker);

    // 机腹两侧的方形大进气口：嵌进机身（机身截面是菱形，盒子内移后下半截和外半截露在外面），不能悬在机身外
    b.box(1.25, -0.40, 3.0, 1.0, 1.0, 3.8, C.dark);
    b.box(-1.25, -0.40, 3.0, 1.0, 1.0, 3.8, C.dark);

    // 座舱盖
    b.quad(b.vt(V(0, 1.10, 9.0)), b.vt(V(0.52, 0.80, 5.4)),
      b.vt(V(0, 0.66, 3.8)), b.vt(V(-0.52, 0.80, 5.4)), C.canopy);

    return done(b, { span: 15.6, len: 24.0, sweepAlt: null });
  }
});
