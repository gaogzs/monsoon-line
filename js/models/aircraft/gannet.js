/* ============================================================
   F-12「塘鹅」Gannet —— 国土防卫重型战斗机
   宽机身 + 中等后掠的大梯形翼 + 双发 + 外倾双垂尾 + 方形大进气道。
   体型比海燕厚一圈：挂点多、翼根粗，靠结构吃伤害，不靠机动。
   ============================================================ */
Registry.model({
  id: 'gannet', order: 411,
  build: function (L) {
    var V = L.V, C = L.C, MB = L.MB, done = L.done;
    var b = new MB();
    b.fuselage([
      { z: 12.0, w: 0.08, h: 0.08 },
      { z: 9.6, w: 0.55, h: 0.50 },
      { z: 6.2, w: 1.05, h: 0.92 },
      { z: 2.4, w: 1.62, h: 1.40 },
      { z: -2.0, w: 1.90, h: 1.52 },
      { z: -6.5, w: 1.96, h: 1.52 },
      { z: -10.2, w: 1.66, h: 1.28 }
    ], C.body, C.body3);

    // 大梯形翼（前缘中等后掠）
    b.foil(V(1.78, -0.30, 3.0), V(8.6, -0.55, -4.4),
      V(8.6, -0.55, -6.0), V(1.90, -0.30, -6.6), C.wing);
    b.foilM(V(1.78, -0.30, 3.0), V(8.6, -0.55, -4.4),
      V(8.6, -0.55, -6.0), V(1.90, -0.30, -6.6), C.wing);

    // 外倾双垂尾
    b.foil(V(0.95, 1.10, -7.0), V(2.70, 3.90, -10.2),
      V(2.70, 3.90, -11.2), V(0.95, 1.10, -8.8), C.wing2);
    b.foilM(V(0.95, 1.10, -7.0), V(2.70, 3.90, -10.2),
      V(2.70, 3.90, -11.2), V(0.95, 1.10, -8.8), C.wing2);

    // 全动平尾
    b.foil(V(1.9, 0.05, -7.4), V(4.4, -0.15, -10.4),
      V(4.4, -0.15, -11.4), V(1.9, 0.05, -9.2), C.wing2);
    b.foilM(V(1.9, 0.05, -7.4), V(4.4, -0.15, -10.4),
      V(4.4, -0.15, -11.4), V(1.9, 0.05, -9.2), C.wing2);

    // 双尾喷口
    b.tube(V(0.98, -0.10, -10.2), V(0.98, -0.10, -11.5), 0.54, 0.50, 8, C.nozzle, C.darker);
    b.tube(V(-0.98, -0.10, -10.2), V(-0.98, -0.10, -11.5), 0.54, 0.50, 8, C.nozzle, C.darker);

    // 方形大进气道（翼根下，比海燕宽）
    b.box(1.25, -0.40, 1.6, 0.62, 1.10, 4.4, C.dark);
    b.box(-1.25, -0.40, 1.6, 0.62, 1.10, 4.4, C.dark);

    // 座舱盖
    b.quad(b.vt(V(0, 1.10, 9.0)), b.vt(V(0.52, 0.80, 5.4)),
      b.vt(V(0, 0.66, 3.8)), b.vt(V(-0.52, 0.80, 5.4)), C.canopy);

    return done(b, {
      span: 17.2, len: 23.5,
      sweepAlt: null
    });
  }
});
