/* ============================================================
   ROK-40「巨砾」—— 石林的重型轰炸机

   又大又慢：四台发动机、平直翼、载弹量比一架战斗机重十倍。
   它不参与空战 —— 从进场到投弹到脱离，全程沿剧本给的航线飞，
   不选目标、不追人、不规避。

   命名沿用石林的岩石系列：「巨砾」。
   ============================================================ */
Registry.model({
  id: 'boulder', order: 470,
  build: function (L) {
    var V = L.V, C = L.C, MB = L.MB, done = L.done;
    var b = new MB();
    /* 2.5 重做：机长 44 → 58 m、翼展 46 → 54 m，机身更细长。
       真实对比（B-1B 对 F-16）机长约 2.8 倍、翼展约 3–4 倍；原来机长只有战斗机的 2 倍，
       不显得"重"。z：机头 +26，尾锥 −32。 */
    b.fuselage([
      { z: 26.0, w: 1.2, h: 1.4 },      // 机头
      { z: 22.5, w: 2.4, h: 2.4 },
      { z: 16.0, w: 3.2, h: 3.0 },
      { z: 6.0, w: 3.5, h: 3.2 },
      { z: -4.0, w: 3.5, h: 3.2 },
      { z: -14.0, w: 3.0, h: 2.9 },
      { z: -24.0, w: 2.3, h: 2.3 },
      { z: -32.0, w: 1.5, h: 1.6 }      // 尾锥
    ], C.body, C.body3);

    // 平直大展弦比翼 —— 轰炸机不需要机动，只需要升力和航程
    b.foil(V(3.6, 0.4, 7.0), V(27.0, 0.0, 3.2),
      V(27.0, 0.0, -2.4), V(3.8, 0.4, -6.0), C.wing);
    b.foilM(V(3.6, 0.4, 7.0), V(27.0, 0.0, 3.2),
      V(27.0, 0.0, -2.4), V(3.8, 0.4, -6.0), C.wing);

    // 四台翼下吊挂发动机
    var eng = [[9.5, 5.5], [17.5, 5.0]];
    var k, e, side;
    for (k = 0; k < 2; k++) {
      e = eng[k];
      for (side = -1; side <= 1; side += 2) {
        b.tube(V(side * e[0], -1.2, e[1] + 2.6), V(side * e[0], -1.2, e[1] - 2.4),
          1.5, 1.4, 8, C.grey2, C.dark);
        b.tube(V(side * e[0], -1.2, e[1] - 2.4), V(side * e[0], -1.2, e[1] - 3.4),
          1.1, 1.0, 8, C.nozzle, C.darker);
      }
    }

    // 高大方正的垂尾
    b.foil(V(0, 1.6, -24.0), V(0, 10.0, -29.0),
      V(0, 10.0, -30.6), V(0, 1.6, -27.5), C.wing2);
    // 平尾
    b.foil(V(1.4, 0.8, -25.0), V(9.5, 0.4, -28.5),
      V(9.5, 0.4, -29.8), V(1.4, 0.8, -28.0), C.wing2);
    b.foilM(V(1.4, 0.8, -25.0), V(9.5, 0.4, -28.5),
      V(9.5, 0.4, -29.8), V(1.4, 0.8, -28.0), C.wing2);

    // 领航员的玻璃机头
    b.quad(b.vt(V(0, 1.5, 26.4)), b.vt(V(1.1, 0.9, 21.0)),
      b.vt(V(0, 0.3, 19.0)), b.vt(V(-1.1, 0.9, 21.0)), C.canopy);

    // 腹部弹舱（前后两对挂点 A1 / A2 就在里面）
    b.box(0, -2.0, 1.5, 3.0, 1.2, 14.0, C.dark, C.darker);

    return done(b, { span: 54, len: 58 });
  }
});
