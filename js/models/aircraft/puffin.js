/* ============================================================
   J-4「海鹦」Puffin —— 空中整备机
   上单翼、双发、T 形尾，机头一只又圆又大的"喙"（海鹦的脸），翼尖各吊一只整备吊舱，
   机腹一个鼓包（整备物资）。慢，大，没有任何武器。
   ============================================================ */
Registry.model({
  id: 'puffin', order: 442,
  build: function (L) {
    var V = L.V, C = L.C, MB = L.MB, done = L.done;
    var b = new MB();
    b.fuselage([
      { z: 14.4, w: 0.60, h: 0.60 },
      { z: 12.6, w: 1.50, h: 1.40 },
      { z: 9.0, w: 2.20, h: 2.00 },
      { z: 0.0, w: 2.50, h: 2.30 },
      { z: -8.0, w: 2.40, h: 2.10 },
      { z: -14.0, w: 1.20, h: 1.10 }
    ], C.body, C.body3);

    function wing(p1, p2, p3, p4, col) { b.foil(p1, p2, p3, p4, col); b.foilM(p1, p2, p3, p4, col); }
    // 上单翼：轻微后掠，翼展 30 m
    wing(V(2.4, 1.7, 3.5), V(15.0, 2.0, 1.8), V(15.0, 2.0, -1.4), V(2.4, 1.7, -3.6), C.wing);

    // T 形尾
    b.foil(V(0, 2.0, -9), V(0, 8.2, -13), V(0, 8.2, -14.6), V(0, 2.0, -14.2), C.wing2);
    wing(V(0, 8.2, -12.6), V(5.6, 8.4, -13.8), V(5.6, 8.4, -14.8), V(0, 8.2, -14.6), C.wing2);   // 翼根 x = 0：压在垂尾上，不悬空

    // 翼下双发
    for (var side = -1; side <= 1; side += 2) {
      var ex = side * 6.4;
      b.tube(V(ex, 0.8, 4.2), V(ex, 0.8, -3.2), 1.05, 1.0, 8, C.body3, C.dark);
      b.tube(V(ex, 0.8, -3.2), V(ex, 0.8, -4.6), 0.8, 0.7, 8, C.nozzle, C.darker);
      // 翼尖整备吊舱（长条形，黄色标识）
      b.tube(V(side * 14.2, 1.75, 2.6), V(side * 14.2, 1.75, -3.4), 0.55, 0.50, 8, C.wing2, C.dark);
    }

    // 机头的"喙"（亮色，海鹦的脸）与机腹整备物资鼓包
    b.box(0, -0.1, 13.0, 1.4, 1.2, 2.6, C.wing2);
    b.box(0, -2.5, -0.5, 3.0, 0.9, 12, C.body3);

    // 座舱盖
    b.quad(b.vt(V(0, 1.7, 11.4)), b.vt(V(0.9, 1.5, 9.6)),
      b.vt(V(0, 1.3, 8.6)), b.vt(V(-0.9, 1.5, 9.6)), C.canopy);

    return done(b, { span: 30, len: 29.6, sweepAlt: null });
  }
});
