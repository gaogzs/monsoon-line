/* ============================================================
   D-14「旗鱼」Sailfish —— 平流层制空战斗机
   菱形翼 + V 尾；翼载 240 kg/m²，为 20 km 高度权衡出来的形状
   ============================================================ */
Registry.model({
  id: 'sailfish', order: 20,
  build: function (L) {
    var V = L.V, C = L.C, MB = L.MB, done = L.done;
    var b = new MB();
    b.fuselage([
      { z: 11.6, w: 0.10, h: 0.08 },
      { z: 8.2, w: 0.62, h: 0.40 },
      { z: 4.0, w: 1.18, h: 0.56 },
      { z: -2.0, w: 1.48, h: 0.70 },
      { z: -7.0, w: 1.22, h: 0.64 },
      { z: -10.6, w: 0.96, h: 0.56 }
    ], C.body2, C.body3);

    // 菱形主翼（前缘 48°，后缘前掠）
    b.foil(V(1.05, -0.05, 2.2), V(6.9, -0.10, -5.6), V(6.9, -0.10, -7.2), V(1.05, -0.05, -6.6), C.wing);
    b.foilM(V(1.05, -0.05, 2.2), V(6.9, -0.10, -5.6), V(6.9, -0.10, -7.2), V(1.05, -0.05, -6.6), C.wing);

    // V 尾（兼当平尾）
    b.foil(V(0.98, 0.42, -6.0), V(3.7, 2.45, -8.7), V(3.7, 2.45, -10.0), V(0.98, 0.42, -9.0), C.wing2);
    b.foilM(V(0.98, 0.42, -6.0), V(3.7, 2.45, -8.7), V(3.7, 2.45, -10.0), V(0.98, 0.42, -9.0), C.wing2);

    // 主翼下大边条
    b.foil(V(0.4, -0.5, 3.4), V(2.2, -0.55, 1.2), V(2.2, -0.55, -2.0), V(0.4, -0.5, -1.0), C.body3);
    b.foilM(V(0.4, -0.5, 3.4), V(2.2, -0.55, 1.2), V(2.2, -0.55, -2.0), V(0.4, -0.5, -1.0), C.body3);

    b.quad(b.pt(0, 0.58, 6.4), b.pt(0.50, 0.68, 4.6), b.pt(0, 1.22, 3.2), b.pt(-0.50, 0.68, 4.6), C.canopy);

    b.tube(V(0.42, 0, -10.6), V(0.42, 0, -11.3), 0.34, 0.32, 8, C.nozzle, C.darker);
    b.tube(V(-0.42, 0, -10.6), V(-0.42, 0, -11.3), 0.34, 0.32, 8, C.nozzle, C.darker);

    return done(b, { span: 13.8, len: 22.9 });
  }
});
