/* ============================================================
   ROK-6「砾石」—— 下游廉价无人机
   粗短的圆管机身 + 一对后掠直翼 + 双垂尾，机头是平的天线罩，没有座舱。
   ============================================================ */
Registry.model({
  id: 'gravel', order: 455,
  build: function (L) {
    var V = L.V, C = L.C, MB = L.MB, done = L.done;
    var b = new MB();
    b.fuselage([
      { z: 3.4, w: 0.20, h: 0.20 },
      { z: 2.4, w: 0.46, h: 0.44 },
      { z: 0.4, w: 0.58, h: 0.52 },
      { z: -2.0, w: 0.52, h: 0.48 },
      { z: -3.4, w: 0.36, h: 0.34 }
    ], C.body2, C.body3);
    // 后掠直翼
    b.foil(V(0.58, -0.05, 0.9), V(3.5, -0.10, -1.0), V(3.5, -0.10, -1.9), V(0.58, -0.05, -1.8), C.wing);
    b.foilM(V(0.58, -0.05, 0.9), V(3.5, -0.10, -1.0), V(3.5, -0.10, -1.9), V(0.58, -0.05, -1.8), C.wing);
    // 双垂尾（外倾）
    b.foil(V(0.34, 0.30, -2.4), V(0.90, 1.50, -3.4), V(0.90, 1.50, -3.9), V(0.34, 0.30, -3.5), C.wing2);
    b.foilM(V(0.34, 0.30, -2.4), V(0.90, 1.50, -3.4), V(0.90, 1.50, -3.9), V(0.34, 0.30, -3.5), C.wing2);
    // 机头天线罩（深色，不是座舱盖）
    b.box(0, 0.30, 2.6, 0.5, 0.26, 0.9, C.dark);
    b.tube(V(0, 0, -3.3), V(0, 0, -3.9), 0.26, 0.22, 8, C.nozzle, C.darker);
    return done(b, { span: 7.2, len: 7.6 });
  }
});
