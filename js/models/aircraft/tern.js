/* ============================================================
   G-8「燕鸥」Tern —— 战斗轰炸机
   中等后掠的中单翼 + 单垂尾 + 双发并列的大尾喷口 + 机腹两排挂架的平底。
   比海燕短粗、比鲣鸟干净：外形像一只收了翅膀的燕鸥。
   ============================================================ */
Registry.model({
  id: 'tern', order: 412,
  build: function (L) {
    var V = L.V, C = L.C, MB = L.MB, done = L.done;
    var b = new MB();
    b.fuselage([
      { z: 10.4, w: 0.08, h: 0.08 },
      { z: 8.2, w: 0.50, h: 0.46 },
      { z: 5.4, w: 0.96, h: 0.86 },
      { z: 2.0, w: 1.38, h: 1.18 },
      { z: -2.0, w: 1.52, h: 1.24 },
      { z: -6.0, w: 1.50, h: 1.22 },
      { z: -8.8, w: 1.30, h: 1.06 }
    ], C.body, C.body3);

    // 后掠中单翼
    b.foil(V(1.44, -0.25, 2.2), V(6.6, -0.45, -3.2),
      V(6.6, -0.45, -4.7), V(1.52, -0.25, -5.4), C.wing);
    b.foilM(V(1.44, -0.25, 2.2), V(6.6, -0.45, -3.2),
      V(6.6, -0.45, -4.7), V(1.52, -0.25, -5.4), C.wing);

    // 单垂尾
    b.foil(V(0, 0.95, -5.4), V(0, 4.1, -8.6),
      V(0, 4.1, -9.6), V(0, 0.95, -8.2), C.wing2);

    // 平尾
    b.foil(V(1.40, 0.05, -6.2), V(3.6, -0.15, -8.8),
      V(3.6, -0.15, -9.7), V(1.40, 0.05, -8.0), C.wing2);
    b.foilM(V(1.40, 0.05, -6.2), V(3.6, -0.15, -8.8),
      V(3.6, -0.15, -9.7), V(1.40, 0.05, -8.0), C.wing2);

    // 双发并列尾喷口
    b.tube(V(0.60, -0.10, -8.6), V(0.60, -0.10, -9.8), 0.50, 0.46, 8, C.nozzle, C.darker);
    b.tube(V(-0.60, -0.10, -8.6), V(-0.60, -0.10, -9.8), 0.50, 0.46, 8, C.nozzle, C.darker);

    // 进气道（两侧翼根）
    b.box(1.08, -0.34, 1.2, 0.50, 0.92, 3.6, C.dark);
    b.box(-1.08, -0.34, 1.2, 0.50, 0.92, 3.6, C.dark);

    // 座舱盖
    b.quad(b.vt(V(0, 0.96, 7.6)), b.vt(V(0.42, 0.70, 4.8)),
      b.vt(V(0, 0.56, 3.6)), b.vt(V(-0.42, 0.70, 4.8)), C.canopy);

    return done(b, {
      span: 13.2, len: 20.2,
      sweepAlt: null
    });
  }
});
