/* ============================================================
   G-8「燕鸥」Tern —— 战斗轰炸机（低空高速突防型）
   现实里的战斗轰炸机（狂风、F-111、苏-34 一类）都有这几样，这里一样一样画出来：
     双座        飞行员 + 武器系统官，一条很长的串列座舱盖
     宽扁的机身  机腹是平的，前后两排挂弹位（串列）
     大后掠翼    固定的大翼套 + 后掠到底的外翼（变后掠翼的低空突防位置），翼下有挂点
     单垂尾      又高又直，配一对低位的全动平尾
     长机头      大雷达罩，下面一只目标指示吊舱；机尾一根电子战尾刺
   坐标 x 右、y 上、z 机头；长 22 × 展 16 m。
   ============================================================ */
Registry.model({
  id: 'tern', order: 412,
  build: function (L) {
    var V = L.V, C = L.C, MB = L.MB, done = L.done;
    var b = new MB();
    // 机身：宽而扁（半宽大、半高小），机头长而尖
    b.fuselage([
      { z: 11.0, w: 0.08, h: 0.08 },
      { z: 9.0, w: 0.60, h: 0.45 },
      { z: 6.0, w: 1.20, h: 0.85 },
      { z: 2.0, w: 1.80, h: 1.05 },
      { z: -3.0, w: 2.00, h: 1.10 },
      { z: -8.0, w: 1.80, h: 1.00 },
      { z: -10.5, w: 1.30, h: 0.80 }
    ], C.body, C.body3);

    function wing(p1, p2, p3, p4, col) { b.foil(p1, p2, p3, p4, col); b.foilM(p1, p2, p3, p4, col); }

    // 固定的大翼套（机翼根部那块三角形前缘延伸）
    wing(V(1.6, -0.10, 5.0), V(3.4, -0.20, 0.8), V(3.4, -0.20, -2.6), V(1.8, -0.10, -3.0), C.wing);
    // 外翼：后掠到底（约 60°），翼尖弦很短
    wing(V(3.4, -0.25, 0.2), V(8.0, -0.40, -8.2), V(8.0, -0.40, -9.6), V(3.4, -0.25, -3.4), C.wing);

    // 单垂尾：又高又直
    b.foil(V(0, 1.0, -5.5), V(0, 5.6, -10.0), V(0, 5.6, -11.4), V(0, 1.0, -10.2), C.wing2);
    // 低位全动平尾
    wing(V(1.6, -0.10, -8.2), V(5.4, -0.25, -10.8), V(5.4, -0.25, -11.8), V(1.6, -0.10, -10.4), C.wing2);

    // 双发并排的尾喷口 + 机尾电子战尾刺
    b.tube(V(0.75, -0.10, -10.2), V(0.75, -0.10, -11.6), 0.55, 0.50, 8, C.nozzle, C.darker);
    b.tube(V(-0.75, -0.10, -10.2), V(-0.75, -0.10, -11.6), 0.55, 0.50, 8, C.nozzle, C.darker);
    b.tube(V(0, 0.75, -10.0), V(0, 0.80, -13.2), 0.16, 0.05, 6, C.wing2, C.dark);

    // 座舱后方两侧的矩形进气口：嵌进机身（内移，和机身截面相交），不悬在外面
    b.box(1.50, -0.15, -0.2, 0.8, 1.0, 3.2, C.dark);
    b.box(-1.50, -0.15, -0.2, 0.8, 1.0, 3.2, C.dark);

    // 机头下的目标指示吊舱：上移嵌进机头，只露出下半截（机头这里的半高约 0.72）
    b.box(0, -0.75, 7.0, 0.55, 0.45, 1.3, C.dark);

    // 双座串列的长座舱盖
    b.quad(b.vt(V(0, 0.92, 7.8)), b.vt(V(0.58, 0.78, 4.0)),
      b.vt(V(0, 0.74, 1.2)), b.vt(V(-0.58, 0.78, 4.0)), C.canopy);

    return done(b, { span: 16.0, len: 24.2, sweepAlt: null });
  }
});
