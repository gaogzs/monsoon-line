/* ============================================================
   GAL-52「黑曜岩」Obsidian —— 战略制空支援机

   以协和的细长大三角翼为蓝本，不照抄，融合了几样特征，每一样都对应它在游戏里的用途：
     协和     哥特式（前缘弯曲）细长大三角翼、没有平尾、一片垂尾、下垂的机头、翼下并列的两对发动机
              → 高速、转不动的最直观表达；大翼根留出弹舱；一眼和所有带平尾的战斗机区分开
     XB-70    机头两侧的小鸭翼、下垂的翼尖
              → 把轮廓再拉远一点，不只是协和的缩小版
     自定     背部一条长长的电子战整流罩（干扰场的视觉标志）、机腹三个长弹舱的舱门缝
   坐标 x 右、y 上、z 机头；长 47 × 展 19.2 m。
   ============================================================ */
Registry.model({
  id: 'obsidian', order: 441,
  build: function (L) {
    var V = L.V, C = L.C, MB = L.MB, done = L.done;
    var b = new MB();

    // 机身：细长，机头下垂（截面 y 是中心的竖直偏移）
    b.fuselage([
      { z: 23, w: 0.18, h: 0.18, y: -0.9 },
      { z: 19, w: 0.70, h: 0.60, y: -0.5 },
      { z: 14, w: 1.20, h: 1.00, y: -0.1 },
      { z: 8, w: 1.60, h: 1.35 },
      { z: 0, w: 1.90, h: 1.50 },
      { z: -10, w: 2.00, h: 1.50 },
      { z: -18, w: 1.70, h: 1.30 },
      { z: -24, w: 1.00, h: 0.90 }
    ], C.body, C.body3);

    function wing(p1, p2, p3, p4, col) { b.foil(p1, p2, p3, p4, col); b.foilM(p1, p2, p3, p4, col); }

    // 哥特翼：三段拼出弯曲的前缘（越靠翼根后掠越大），后缘是直的；最外一段翼尖下垂。
    // 翼根前缘退到 z = 8：机头在翼前伸出一大截，又细又长（协和翼展 / 机长约 0.4，这里 19.2 / 47）
    wing(V(1.3, -0.2, 8), V(3.4, -0.3, -1), V(3.4, -0.3, -22), V(1.6, -0.2, -22), C.wing);
    wing(V(3.4, -0.3, -1), V(6.0, -0.3, -9), V(6.0, -0.3, -22), V(3.4, -0.3, -22), C.wing);
    wing(V(6.0, -0.3, -9), V(9.6, -1.5, -17.5), V(9.6, -1.5, -22), V(6.0, -0.3, -22), C.wing2);

    // 机头两侧的小鸭翼（Tu-144 / XB-70 式）：贴着细长的机头，不能做大，大了就成了鸭式三角翼战斗机
    wing(V(1.0, 0.2, 17), V(3.4, 0.1, 15.2), V(3.4, 0.1, 14.0), V(1.0, 0.2, 14.6), C.wing2);

    // 单片大垂尾，没有平尾
    b.foil(V(0, 1.5, -12), V(0, 9.0, -21), V(0, 9.0, -24.2), V(0, 1.5, -22.5), C.wing2);

    // 翼下并列的两对发动机：每侧一个长短舱，前面两个并排的进气口，后面两个喷口（共四个，伸出后缘）
    for (var side = -1; side <= 1; side += 2) {
      b.box(side * 3.9, -1.5, -12.5, 3.0, 2.0, 19, C.body3);       // z -3 … -22
      for (var k = 0; k < 2; k++) {
        var ex = side * (3.2 + k * 1.4);
        b.box(ex, -1.5, -3.1, 1.2, 1.7, 0.5, C.dark);
        b.tube(V(ex, -1.5, -22), V(ex, -1.5, -25.5), 0.68, 0.58, 8, C.nozzle, C.darker);
      }
    }

    // 背部长电子战整流罩（前端收尖）：干扰场的视觉标志
    b.box(0, 1.9, -3, 1.0, 0.8, 18, C.body3);
    b.box(0, 1.65, 7.4, 0.7, 0.5, 2.6, C.body3);

    // 机腹三个长弹舱的舱门缝
    var bays = [10, 0, -10];
    for (var bi = 0; bi < bays.length; bi++) b.box(0, -1.40, bays[bi], 1.3, 0.06, 7.0, C.dark);

    // 驾驶舱：下垂鼻后面一小段，低矮的两块风挡（协和的风挡很小，鼻子一放下来就是为了看路）
    b.flightDeck({ z0: 17.0, dz: 1.2, len: 2.2, back: 1.2, hw: 0.5, hh: 0.28, body: C.body, glass: C.canopy });

    return done(b, { span: 19.2, len: 47, sweepAlt: null });
  }
});
