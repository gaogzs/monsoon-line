/* ============================================================
   ROK-27「燧石」Flint —— 下游第 4 战术联队制式重型截击机
   翼身融合 + 双垂尾；下游机型普遍更重、更粗、更能忍受粗暴维护
   ============================================================ */
Registry.model({
  id: 'schist', order: 40,
  build: function (L) {
    var V = L.V, C = L.C, MB = L.MB, done = L.done;
    var b = new MB();
    b.fuselage([
      { z: 11.0, w: 0.12, h: 0.12 },
      { z: 8.0, w: 0.66, h: 0.62 },
      { z: 4.6, w: 1.24, h: 0.98 },
      { z: 0.8, w: 1.72, h: 1.14 },
      { z: -3.4, w: 1.64, h: 1.10 },
      { z: -7.6, w: 1.20, h: 0.96 },
      { z: -10.2, w: 1.15, h: 1.01 }
    ], C.body3, C.dark);

    // 后掠翼
    b.foil(V(1.55, -0.20, 1.8), V(7.4, -0.60, -2.6), V(7.4, -0.60, -4.6), V(1.55, -0.20, -4.2), C.body2);
    b.foilM(V(1.55, -0.20, 1.8), V(7.4, -0.60, -2.6), V(7.4, -0.60, -4.6), V(1.55, -0.20, -4.2), C.body2);

    // 平尾
    b.foil(V(1.15, -0.10, -7.0), V(3.9, 0.05, -8.9), V(3.9, 0.05, -10.1), V(1.15, -0.10, -9.4), C.body2);
    b.foilM(V(1.15, -0.10, -7.0), V(3.9, 0.05, -8.9), V(3.9, 0.05, -10.1), V(1.15, -0.10, -9.4), C.body2);

    // 双垂尾：外倾约 4°。翼根 x = 0.85 要落在尾部机身半宽（z = -9.4 处 1.03）以内，
    // 否则 rootFins 沿翼面推不进机身，后缘翼根会被朝轴线拽歪（以前 x = 1.10，显示成 14°，前后缘还不共面）
    b.foil(V(0.85, 0.92, -6.0), V(1.04, 3.70, -7.8), V(1.04, 3.70, -9.6), V(0.85, 0.92, -9.4), C.body2);
    b.foilM(V(0.85, 0.92, -6.0), V(1.04, 3.70, -7.8), V(1.04, 3.70, -9.6), V(0.85, 0.92, -9.4), C.body2);

    // 尾锥 + 双发布局
    b.tube(V(0.50, 0, -10.2), V(0.50, 0, -11.0), 0.41, 0.40, 8, C.nozzle, C.darker);
    b.tube(V(-0.50, 0, -10.2), V(-0.50, 0, -11.0), 0.41, 0.40, 8, C.nozzle, C.darker);

    b.quad(b.pt(0, 0.90, 5.8), b.pt(0.58, 1.02, 4.2), b.pt(0, 1.66, 2.9), b.pt(-0.58, 1.02, 4.2), C.canopy);

    return done(b, { span: 14.8, len: 22.0 });
  }
});
