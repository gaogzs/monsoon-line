function canCarry(ac, w) {
  if (!w || !w.needs || !w.needs.length) return true;
  var caps = (ac && ac.caps) || [];
  for (var i = 0; i < w.needs.length; i++) {
    if (caps.indexOf(w.needs[i]) < 0) return false;
  }
  return true;
}

