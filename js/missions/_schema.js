/* ============================================================
   方位约定（axis）

   每一关的战场都按同一种摆法写：玩家在 −z 一侧、机头朝 +z，
   敌方在 +z 一侧。为了让每一关的战线**不是同一条线**，
   世界坐标并不固定指北 —— 每关用 axis 声明"世界 +z 的真方位"（度）：
     axis 180 = 敌人从正南来，玩家背后是北；axis 225 = 敌从西南来……
   设定上上游（公约）在北、下游（同盟）在南，所以多数关卡的 axis 在
   135–225 之间。罗盘、方位报读（game.js bearing()）、简报地图都按它换算；
   物理、AI、触发器仍然只看世界坐标，所以改 axis 不会改变玩法。
   简报文案里的方向词（北 / 西南 / 航向 xxx°）必须按 axis 换算后的真方位写。

   时间与天色（可选）：
     time: { hour: 15.5 }          当地太阳时（0–24，北纬 12°、春分近似）；缺省 = 现有外观
     sun:  { az: 250, el: 20 }     直接给太阳：真方位 °（北 0 顺时针）与高度 °，优先于 time
   太阳位置、天空、海面、雾、云色按太阳高度在 Shading 的环境预设之间插值
   （正午 / 上午午后 / 金色时段 / 黄昏），不做夜战；真方位按本关 axis 换成世界方向。
   注意 mission.time 是"一天中的时刻"，与 world.time（本局已过时间）无关。

   战区边界（每关都写）：
     arena: { cx, cz, half, warn }   世界米，方形；half = 真边界到中心的距离，warn = 警告区宽度
   越过边界玩家会渐黑并失败，AI 在警告区内被软转向拉回；取值依据见 tools/test/probes/probe-extent.js。
   判定见 js/engine/world/arena.js（Arena.state / validate）。

   整备点（每关都写）：mission.resupply = [ 条目… ]，条目二选一：
     { ref, r, hold, uses, swap }   单位整备点：ref 是 spawnShip / spawnPlatform 的 o.ref，
                                    那个单位必须是 team 0 且带 resupply 标签；r 水平半径（m），
                                    hold 驻留秒数，uses 可用次数，swap 是否弹出重选挂载界面
     { edge, hold, uses, swap }     界外整备区：edge = '+x' | '-x' | '+z' | '-z'，玩家身处战场那一侧的
                                    警告区或界外区（Arena.inEdge）时驻留 hold 秒就整备。
                                    关卡里没有母舰 / 机场时用它，具体哪一侧按关卡写（玩家身后通常是 -z）。
                                    整备区里不触发越界渐黑；uses 用完才恢复。

   map 里的标记用**世界坐标**，与 spawn 里的数一致；type 'start' 是玩家进入点
   （dir = 世界航向，0 = +z）。地图由 drawMap 旋到北朝上。
   ============================================================ */
