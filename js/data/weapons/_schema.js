/* ============================================================
   挂载属性
   —— 单独放在这里而不是塞进 WEAPONS 表里，是为了让"这个弹能挂在
   哪些挂点上、一个挂点带几发、有多重"集中在一处，一眼横着能比较。

     fits     能挂的挂点类型（**玩家机库**能选的）
              tip   翼尖（轻，只受得起小型空空弹）
              light 通用挂架
              heavy 重挂点（大型弹只有这里挂得下）
              belly 机腹（吊舱与对地弹）
     npcFits  同一件事，但给**NPC 的制式装机**用（写在 WEAPONS 各条目里，
              不在 STORE_ATTR —— 下游弹的 fits 是空的，不经过这张表）。
              见下面"两张 fits 表"。
     perPoint 单个挂载点提供几发
     mass     单件重量 kg，用来算挂载对机动性的拖累

     两张 fits 表

     玩家的可挂判据（机库 UI、resolveLoadout、loadoutMass）只认 fits；
     NPC 的实体挂载（game.js 的 pushStores → Ent.fitsKind）读 npcFits，
     没写 npcFits 的武器退回 fits。

     为什么不能合成一张：下游弹（dl4 / dl6 / vbn / …）的 fits 是空数组，
     它的语义是"上游拿不到实物，玩家挂不上"，不是"挂不上"。
     合成一张的话，要么敌机机翼永远是干净的（读 fits 的结果），
     要么把空空弹画到只有机腹挂点的支援机上（删掉检查的结果）。
   ============================================================ */
/* ============================================================
   挂载外观（纯美术，不影响任何数值）
   len / dia：弹体长度与直径（米）。格斗弹短细、远程弹粗长，
              一眼能从翼下看出这架飞机是去狗斗还是去守门。
   fin：  'strake' 长边条翼（格斗） / 'small' 小弹翼（中远）
          / 'cruise' 平直弹翼（巡航弹）/ 'bomb' 炸弹尾翼
   boost：尾部助推段（超远程 / 反舰）
   nose： 'dual' 头部改装（TOR-3）：导引头罩 + 后面一段加粗的战斗部，飞行中与挂架上都画这个样子
   rack： 一个挂架上**看得见**的弹数 —— 只给单次齐射多发的武器（= salvo），
          单发武器哪怕一个挂点装好几发也画成一枚（perPoint 是弹库，不是外观）
   rdia： 巢式武器离架后单发的直径（dia 是整个巢）；MODELS.round 用它
   nest： 'tube' 圆筒火箭巢 / 'box' 方形发射巢；cells 是管口数
   3D（MODELS.store / MODELS.round）与识别图（PLANFORM.drawStore）读同一份。
   ============================================================ */
/* ============================================================
   导引品质
   lead = 0   纯追踪 —— 傻追着目标当前的位置，目标一拐弯就甩掉
   lead = 1   完全预测 —— 飞向解算出来的最优拦截点

   这比转弯率更能体现"这枚弹聪不聪明"：一枚转弯率一般但预测准的弹，
   打机动目标反而比一枚只会死咬尾巴的灵活弹更管用。
   基础弹（TOR-2）刻意做得很笨，改进型的钱基本都花在这里。
   ============================================================ */
