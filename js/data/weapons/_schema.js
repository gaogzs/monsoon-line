/* ============================================================
   干扰弹的抗性：箔丝概率（flareRD）

   干扰弹是**热焰弹 + 箔丝**一起投放的：前者骗红外导引头，后者骗雷达。
   所以同一枚弹对这两种导引头其实有两个不同的"被骗概率"：

     flare    热焰弹 —— 红外导引头（也是所有导引头的缺省值）
     flareRD  箔丝   —— 雷达导引头

   设定 8.3 写的是"雷达导引头有多普勒滤波，能滤掉静止的箔丝回波，
   所以雷达弹整体上比红外弹难骗"。而 `flare` 当初是逐个按
   "这枚弹好不好骗"手调的，没有按导引头排序，于是整体反了过来：
   雷达弹平均 0.66，比红外弹的 0.44 **更容易**被骗。

   这张表把**意图**补上，而且不动 `flare` 本身 —— 后者仍然是
   "这枚弹对热焰弹有多脆弱"，语义与既有的断言（TOR-4 最难骗）保持一致。

   取值原则：
     · 空空的雷达弹整体低于红外弹均值（0.44），其中 CLA-4 最低
       —— 设定里点名它是"能与最好的红外弹比肩"的那一枚
     · 对地 / 反大型弹保持高值：它们不装抗干扰设备，也没必要装
   ============================================================ */
