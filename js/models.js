          var hx = -bw / 2 + cw * (cx2 + 0.5), hy = -bh + cw * (cy2 + 0.5);
          // 管口：伸出一点的弹头
          b.tube(V(hx, hy, L / 2), V(hx, hy, L / 2 + 0.22), r, r * 0.15, 6, C.white, C.metal);
